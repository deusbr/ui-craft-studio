'use strict';

const { PLATFORM_GUIDELINES, GITHUB_ECOSYSTEM_REFERENCES, ANTI_SLOP_BAN_LIST } = require('./design-library.cjs');

function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function buildDesignMd(spec) {
  const { appName, brief, direction, platforms, screens, projectScan, contrastAudit } = spec;
  const p = direction.palette;
  const t = direction.typography;

  const contrastRows = (contrastAudit?.checks || [])
    .map((c) => `| \`${c.id}\` | \`${c.fg}\` on \`${c.bg}\` | ${c.ratio}:1 | ${c.aaPass ? 'PASS (AA)' : 'FAIL'} |`)
    .join('\n');

  const platformSections = platforms
    .map((pid) => {
      const g = PLATFORM_GUIDELINES[pid];
      if (!g) return '';
      return `### ${g.name} (${g.viewport.width}x${g.viewport.height})\n${g.rules.map((r) => `- ${r}`).join('\n')}`;
    })
    .filter(Boolean)
    .join('\n\n');

  const screenList = screens
    .map((s, i) => `${i + 1}. **${s.title}** (\`${s.id}\`) — ${s.purpose} | Primary CTA: *${s.primaryAction}*`)
    .join('\n');

  const projectContextBlock = projectScan?.detected
    ? `- **Scanned Repo:** \`${projectScan.projectName}\` (${projectScan.frameworks.join(', ') || 'Generic'})\n- **UI Libraries:** ${projectScan.uiLibraries.join(', ') || 'Custom CSS'}\n- **Existing Tokens Detected:** ${projectScan.designTokens?.colors?.slice(0, 6).join(', ') || 'None'}`
    : '- **Scope:** Greenfield product specification (no local codebase scanned)';

  return `# DESIGN.md — ${appName}

> Generated by **ui-craft-studio** | Aesthetic Direction: **${direction.name}** (\`${direction.id}\`)
> Inspired by \`google-labs-code/design.md\`, \`pbakaus/impeccable\`, \`ui-ux-pro-max-skill\`, and \`AntiSlopUI\`.

## 1. Product Essence & Project Context
- **Product Brief:** ${brief}
${projectContextBlock}
- **Target Platforms:** ${platforms.join(' + ')}

## 2. Atmosphere & Layout Strategy
- **Visual Direction:** ${direction.atmosphere}
- **Density:** \`${direction.density}\`
- **Surface Strategy:** ${direction.surfaceStrategy}
- **Motion Physics:** ${direction.motion}

## 3. Semantic Color Tokens & WCAG 2.1 Verification
| Token Role | Hex | Usage |
| :--- | :--- | :--- |
| \`--bg\` | \`${p.bg}\` | Primary canvas background |
| \`--surface\` | \`${p.surface}\` | Cards, panels, and navigation containers |
| \`--surface-elevated\` | \`${p.surfaceElevated}\` | Active rows, popovers, command bar |
| \`--border\` | \`${p.border}\` | 1px structural hairlines |
| \`--text\` | \`${p.text}\` | Primary readable text |
| \`--muted\` | \`${p.muted}\` | Secondary labels & metadata |
| \`--accent\` | \`${p.accent}\` | Single decisive focal CTA color |
| \`--accent-text\` | \`${p.accentText}\` | Text inside primary CTA buttons |
| \`--success\` / \`--warning\` / \`--danger\` | \`${p.success}\` / \`${p.warning}\` / \`${p.danger}\` | Semantic status feedback |

| Contrast Check | Pair | Ratio | WCAG AA |
| :--- | :--- | :--- | :--- |
${contrastRows}

## 4. Expressive Typography Pairing
- **Display:** \`${t.display}\`
- **Body:** \`${t.body}\`
- **Monospace:** \`${t.mono}\`
- **Rationale:** ${t.rationale}

## 5. Multi-Screen Flow & Interactive States
${screenList}

**Mandatory Interactive States per Screen:** \`populated\`, \`loading\` (skeletons), \`empty\` (actionable CTA), and \`error\` (inline retry).

## 6. Platform Ergonomics
${platformSections}

## 7. Anti-AI-Slop Guardrails (Do Not Violate)
${ANTI_SLOP_BAN_LIST.structuralAntiPatterns.map((r) => `- **FORBIDDEN:** ${r}`).join('\n')}
- **Banned Cliché Hues:** Avoid generic indigo-violet defaults and decorative neon magenta gradients.
- **Banned Marketing Copy:** Never use generic AI hype phrases or placeholder filler text; write concrete domain actions and real metrics.
`;
}

