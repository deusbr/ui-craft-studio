function buildCodeBundles(spec) {
  const { appName, direction, screens, platforms } = spec;
  const p = direction.palette;
  const t = direction.typography;

  const cssTokens = `:root {
  --bg: ${p.bg};
  --surface: ${p.surface};
  --surface-elevated: ${p.surfaceElevated};
  --border: ${p.border};
  --text: ${p.text};
  --muted: ${p.muted};
  --accent: ${p.accent};
  --accent-text: ${p.accentText};
  --font-display: "${t.display}", serif;
  --font-body: "${t.body}", sans-serif;
  --font-mono: "${t.mono}", monospace;
}`;

  const reactTailwind = `import React, { useState } from 'react';

export interface ScreenSpec {
  id: string;
  title: string;
  purpose: string;
  primaryAction: string;
}

const SCREENS: ScreenSpec[] = ${JSON.stringify(screens.map(({ id, title, purpose, primaryAction }) => ({ id, title, purpose, primaryAction })), null, 2)};

export function ${appName.replace(/[^A-Za-z0-9]/g, '') || 'App'}Shell() {
  const [activeScreen, setActiveScreen] = useState(SCREENS[0].id);
  const [uiState, setUiState] = useState<'populated' | 'loading' | 'empty' | 'error'>('populated');
  const current = SCREENS.find((s) => s.id === activeScreen) ?? SCREENS[0];

  return (
    <div className="min-h-screen grid md:grid-cols-[248px_1fr] bg-[var(--bg)] text-[var(--text)]">
      <aside className="hidden md:flex flex-col gap-2 border-r border-[var(--border)] bg-[var(--surface)] p-4">
        <div className="font-bold text-lg px-2 py-1">${appName}</div>
        {SCREENS.map((s) => (
          <button
            key={s.id}
            onClick={() => setActiveScreen(s.id)}
            className={\`min-h-[44px] text-left px-3 py-2 rounded border \${s.id === activeScreen ? 'bg-[var(--surface-elevated)] border-[var(--accent)] font-semibold' : 'border-transparent'}\`}
          >
            {s.title}
          </button>
        ))}
      </aside>
      <main className="p-6 pb-24 md:pb-6 space-y-6">
        <header className="flex flex-wrap items-end justify-between gap-4 border-b border-[var(--border)] pb-4">
          <div>
            <h1 className="text-2xl font-bold">{current.title}</h1>
            <p className="text-sm text-[var(--muted)]">{current.purpose}</p>
          </div>
          <div className="flex gap-2">
            {(['populated', 'loading', 'empty', 'error'] as const).map((st) => (
              <button key={st} onClick={() => setUiState(st)} className="px-3 py-1.5 text-xs rounded border border-[var(--border)]">
                {st}
              </button>
            ))}
          </div>
        </header>
        <section className="rounded border border-[var(--border)] bg-[var(--surface)] p-5">
          State: <strong>{uiState}</strong> — {current.primaryAction}
        </section>
      </main>
    </div>
  );
}`;

  const reactNative = platforms.includes('mobile')
    ? `import React, { useState } from 'react';
import { SafeAreaView, View, Text, Pressable, StyleSheet } from 'react-native';

export const tokens = {
  bg: '${p.bg}',
  surface: '${p.surface}',
  border: '${p.border}',
  text: '${p.text}',
  muted: '${p.muted}',
  accent: '${p.accent}',
  accentText: '${p.accentText}'
};

export function MobileAppShell() {
  const [tab, setTab] = useState('${screens[0].id}');
  return (
    <SafeAreaView style={styles.root}>
      <View style={styles.body}>
        <Text style={styles.title}>${appName}</Text>
        <Text style={styles.sub}>Active screen: {tab}</Text>
      </View>
      <View style={styles.tabBar}>
        ${screens.slice(0, 4).map((s) => `<Pressable onPress={() => setTab('${s.id}')} style={styles.tabBtn}><Text style={styles.tabLabel}>${s.shortLabel || s.title}</Text></Pressable>`).join('\n        ')}
      </View>
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  root: { flex: 1, backgroundColor: tokens.bg },
  body: { flex: 1, padding: 20 },
  title: { fontSize: 24, fontWeight: '700', color: tokens.text },
  sub: { fontSize: 14, color: tokens.muted, marginTop: 6 },
  tabBar: { flexDirection: 'row', borderTopWidth: 1, borderColor: tokens.border, backgroundColor: tokens.surface, paddingVertical: 8 },
  tabBtn: { flex: 1, minHeight: 44, alignItems: 'center', justifyContent: 'center' },
  tabLabel: { fontSize: 12, color: tokens.text }
});`
    : null;

  return {
    cssTokens,
    reactTailwind,
    reactNative
  };
}

